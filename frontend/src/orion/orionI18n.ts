export const ORION_DICTS: Record<string, D> = { ru: RU, en: EN, uk: UK, de: DE };

export function ot(key: string, ...args: (string | number)[]): string {
  let s = (ORION_DICTS[getLang()] || EN)[key] ?? EN[key] ?? key;
  args.forEach((a, i) => (s = s.replace(`{${i}}`, String(a))));
  return s;
}
