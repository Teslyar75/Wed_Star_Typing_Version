export function ot(key: string, ...args: (string | number)[]): string {
  const pack = { ...(ORION_DICTS[getLang()] || EN), ...(EXTRA[getLang()] || EXTRA.en) };
  let s = pack[key] ?? EN[key] ?? EXTRA.en[key] ?? key;
  args.forEach((a, i) => (s = s.replace(`{${i}}`, String(a))));
  return s;
}
